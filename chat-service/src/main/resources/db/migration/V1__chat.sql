-- Chat service schema (database `chat`, owned by the chat service only — ADR-001).
-- Conventions of AR04: snake_case, BIGSERIAL technical ids, native enums with French values.
-- No foreign key to the monolith: customer_ref / agent_ref are JWT `sub` values and
-- reservation_reference is an identifier carried by the client.

CREATE TYPE type_client AS ENUM ('compte', 'invite');
CREATE TYPE statut_conversation AS ENUM ('en_attente', 'en_cours', 'cloturee');
CREATE TYPE type_message AS ENUM ('texte', 'prise_en_charge', 'cloture');
CREATE TYPE role_emetteur AS ENUM ('client', 'agent', 'systeme');

CREATE TABLE conversation (
    id                    BIGSERIAL           PRIMARY KEY,
    customer_ref          TEXT                NOT NULL,
    customer_kind         type_client         NOT NULL,
    reservation_reference TEXT                NULL,
    status                statut_conversation NOT NULL DEFAULT 'en_attente',
    agent_ref             TEXT                NULL,
    -- Idempotency key of "open a conversation" (A6), generated by the client.
    client_request_id     UUID                NOT NULL,
    -- Last seq handed out in this conversation; incremented under the row lock in the same
    -- transaction as the message insert, so seq order == commit order (premise 4, ADR-003).
    last_seq              INT                 NOT NULL DEFAULT 0,
    created_at            TIMESTAMPTZ         NOT NULL DEFAULT now(),
    claimed_at            TIMESTAMPTZ         NULL,
    closed_at             TIMESTAMPTZ         NULL,
    CONSTRAINT conversation_last_seq_ck CHECK (last_seq >= 0),
    -- A4: a customer may close an unclaimed conversation, so only en_cours requires an agent.
    CONSTRAINT conversation_agent_ck CHECK (status <> 'en_cours' OR agent_ref IS NOT NULL),
    CONSTRAINT conversation_client_request_uk UNIQUE (customer_ref, client_request_id)
);

-- Agent queue: oldest en_attente first (P1).
CREATE INDEX conversation_status_created_idx ON conversation (status, created_at);
-- "My conversations": the customer side is served by conversation_client_request_uk (leading column).
CREATE INDEX conversation_agent_ref_idx ON conversation (agent_ref) WHERE agent_ref IS NOT NULL;

CREATE TABLE message (
    conversation_id   BIGINT        NOT NULL REFERENCES conversation (id),
    seq               INT           NOT NULL,
    -- Client-generated for texte (idempotent retries); server-generated UUID for system events (C3).
    client_message_id UUID          NOT NULL,
    type              type_message  NOT NULL,
    sender_role       role_emetteur NOT NULL,
    -- Author of a texte; acting agent (claim) or acting agent/customer (close) for system events (C3).
    sender_ref        TEXT          NOT NULL,
    content           TEXT          NULL,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- Also serves the backfill "WHERE conversation_id = ? AND seq > ? ORDER BY seq".
    CONSTRAINT message_pk PRIMARY KEY (conversation_id, seq),
    CONSTRAINT message_seq_ck CHECK (seq >= 1),
    CONSTRAINT message_client_message_uk UNIQUE (conversation_id, client_message_id),
    CONSTRAINT message_texte_content_ck
        CHECK (type <> 'texte' OR (content IS NOT NULL AND char_length(content) BETWEEN 1 AND 2000)),
    CONSTRAINT message_texte_sender_ck CHECK (type <> 'texte' OR sender_role <> 'systeme'),
    CONSTRAINT message_system_sender_ck CHECK (type = 'texte' OR sender_role = 'systeme'),
    CONSTRAINT message_system_content_ck CHECK (type = 'texte' OR content IS NULL)
);
